/**
 * KETER-TYPE v0.9.8 Phase 1 — Playwright live drive-through (real Chromium).
 *
 * Run from the repo root (after `npm run build`):
 *   node scripts/v098-phase1-playwright-smoke.mjs
 *
 * Flow (light/day theme):
 *  A. Home: the wizard stepper is visible; exactly 5 archetype cards;
 *     the 11 core layout cards are still there underneath.
 *  B. Pick the Shas archetype: the mapped core card (Vilna Shas) is
 *     selected, the calibrated-defaults line appears, and the DOCX hub
 *     switches to the Shas slot matrix (Gemara / Rashi / Tosafot +
 *     "Add Additional Mefaresh") with the Step-3 note.
 *  C. Upload a real Gemara .docx into the Gemara slot (generated by
 *     scripts/v097-make-test-docx.py): the file lands in the slot with
 *     its role preset, and per-file preview counts appear
 *     (words / dibburim) BEFORE Generate is clicked.
 *  D. Developer Mode OFF (default): no QA button in the status bar,
 *     no "Automated Tests" entry anywhere; the score shows as plain
 *     text. (The editor is reached by creating the sample project.)
 *  E. Press Ctrl+Shift+D: the QA button appears in the status bar and
 *     localStorage records developer mode ON. Press again: it is gone
 *     and the stored value is OFF.
 *  F. English mode (fresh page, keter-ui-lang=en): the wizard renders
 *     fully in English — stepper, archetype cards, slot matrix, Step-3
 *     note, Generate button, per-file preview counts ("Words", "Verses")
 *     — and document.dir is 'ltr' with the stepper arrow flipped to →.
 *
 * The Welcome modal ("איך משתמשים בכתר?") opens on first load in a
 * fresh profile and covers Home, so every load dismisses it first via
 * its close button (aria-label "סגור" / "Close").
 *
 * Screenshots: screenshots/v098/<name>.png
 * Exit code 0 = every check passed; 1 = a failure.
 * (Requires the Playwright chromium headless shell.)
 */

import http from 'node:http';
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const DIST = path.join(ROOT, 'dist');
const SHOTS = path.join(ROOT, 'screenshots', 'v098');
fs.mkdirSync(SHOTS, { recursive: true });

// Test .docx files (generated fresh each run, same generator as v0.9.7).
const FIXTURES = fs.mkdtempSync(path.join(os.tmpdir(), 'keter-v098-'));
const gen = spawnSync('python3', [path.join(ROOT, 'scripts', 'v097-make-test-docx.py'), FIXTURES], { encoding: 'utf8' });
if (gen.status !== 0) {
  console.error('docx generator failed:', gen.stdout, gen.stderr);
  process.exit(1);
}

let failures = 0;
let passes = 0;
function check(name, ok, detail = '') {
  if (ok) {
    passes++;
    console.log(`  PASS  ${name}${detail ? ` — ${detail}` : ''}`);
  } else {
    failures++;
    console.log(`  FAIL  ${name}${detail ? ` — ${detail}` : ''}`);
  }
}

const MIME = {
  '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css',
  '.json': 'application/json', '.png': 'image/png', '.svg': 'image/svg+xml',
  '.woff': 'font/woff', '.woff2': 'font/woff2', '.ttf': 'font/ttf',
};

const server = http.createServer((req, res) => {
  const url = new URL(req.url, 'http://localhost');
  let filePath = path.join(DIST, decodeURIComponent(url.pathname));
  if (url.pathname === '/' || !fs.existsSync(filePath) || fs.statSync(filePath).isDirectory()) {
    filePath = path.join(DIST, 'index.html');
  }
  const ext = path.extname(filePath);
  fs.readFile(filePath, (err, data) => {
    if (err) {
      res.writeHead(404);
      res.end('not found');
      return;
    }
    res.writeHead(200, { 'Content-Type': MIME[ext] || 'application/octet-stream' });
    res.end(data);
  });
});

await new Promise((resolve) => server.listen(0, '127.0.0.1', resolve));
const port = server.address().port;
const base = `http://127.0.0.1:${port}`;

const browser = await chromium.launch();
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  // Three buckets: JS exceptions, console errors, failed requests.
  // They are judged separately below — an external font CDN failing
  // in the sandbox (no direct internet) is environmental, but a
  // same-origin asset failing to load would be a real bug.
  const errors = [];
  const failedRequests = [];
  page.on('pageerror', (e) => errors.push(String(e)));
  page.on('console', (m) => {
    if (m.type() === 'error' && !String(m.text()).startsWith('Failed to load resource')) errors.push(m.text());
  });
  page.on('requestfailed', (req) => failedRequests.push(req.url()));

  await page.goto(base + '/', { waitUntil: 'networkidle' });
  await page.waitForTimeout(1500);

  // The Welcome modal opens on first load in a fresh profile and
  // covers Home (it intercepts pointer events). Dismiss it via its
  // close button whenever it is present — after every load.
  async function dismissWelcomeModal(pg) {
    const closeBtn = pg.locator('button[aria-label="סגור"], button[aria-label="Close"]');
    if ((await closeBtn.count()) > 0) {
      await closeBtn.first().click();
      await pg.waitForTimeout(400);
    }
  }
  await dismissWelcomeModal(page);

  // ── A. Home: wizard stepper + 5 archetypes + 11 core cards ──
  check('A wizard stepper visible', await page.locator('[data-testid="sefer-wizard-stepper"]').count() === 1);
  const archetypeCards = page.locator('[data-testid^="new-project-form-home-wizard-archetype-"]');
  check('A exactly 5 archetype cards', (await archetypeCards.count()) === 5, `count=${await archetypeCards.count()}`);
  const coreCards = page.locator('[data-testid="new-project-form-home-core-layouts"] > *');
  check('A 11 core layout cards still present', (await coreCards.count()) === 11, `count=${await coreCards.count()}`);
  check('A no dev text on Home (default OFF)', (await page.locator('text=בדיקות אוטומטיות').count()) === 0);
  await page.screenshot({ path: path.join(SHOTS, '01-home-wizard.png') });

  // ── B. Pick the Shas archetype ──
  await page.locator('[data-testid="new-project-form-home-wizard-archetype-shas"]').click();
  await page.waitForTimeout(600);
  const shasCard = page.locator('[data-testid="new-project-form-home-layout-rav_text"]');
  check('B Shas archetype selects the Vilna core card', await shasCard.evaluate((el) => el.className.includes('bg-[var(--ui-selected-bg)]') || el.outerHTML.includes('CheckCircle2') || el.querySelector('svg') !== null));
  check('B calibrated-defaults line appears', (await page.locator('text=תבנית מכוילת:').count()) >= 1);
  check('B hub switches to the Shas slot matrix', await page.locator('[data-testid="docx-hub-home-wizard-slots"]').count() === 1);
  check('B Gemara slot present', await page.locator('[data-testid="docx-hub-home-slot-gemara"]').count() === 1);
  check('B Rashi slot present', await page.locator('[data-testid="docx-hub-home-slot-rashi"]').count() === 1);
  check('B Tosafot slot present', await page.locator('[data-testid="docx-hub-home-slot-tosafot"]').count() === 1);
  check('B Add Additional Mefaresh button present', await page.locator('[data-testid="docx-hub-home-add-mefaresh"]').count() === 1);
  check('B Step-3 note present and honest', (await page.locator('[data-testid="docx-hub-home-wizard-step3-note"]').count()) === 1);
  check('B Generate button labelled Step 3', (await page.locator('text=צור פריסת ספר (שלב 3)').count()) >= 1);
  await page.screenshot({ path: path.join(SHOTS, '02-shas-slots.png') });

  // ── C. Upload a Gemara .docx into the Gemara slot ──
  const gemaraFile = fs.readdirSync(FIXTURES).find((f) => /gemara/i.test(f));
  check('C fixture Gemara docx exists', !!gemaraFile, `dir=${FIXTURES}`);
  if (gemaraFile) {
    const slotInput = page.locator('[data-testid="docx-hub-home-slot-gemara"] input[type="file"]');
    await slotInput.setInputFiles(path.join(FIXTURES, gemaraFile));
    // Preview parse runs async; the placeholder ("Analysing…") is
    // visible immediately, so wait for the counts text itself.
    await page.waitForFunction(
      () => document.querySelector('[data-testid="docx-hub-home-preview-gemara"]')?.textContent?.includes('מילים'),
      { timeout: 15000 }
    );
    const previewText = await page.locator('[data-testid="docx-hub-home-preview-gemara"]').innerText();
    check('C per-file preview counts shown before Generate', /מילים/.test(previewText) && /ד״ה/.test(previewText), previewText);
    check('C slot shows the uploaded file name', (await page.locator('[data-testid="docx-hub-home-wizard-slots"]').innerText()).includes(gemaraFile));
    await page.screenshot({ path: path.join(SHOTS, '03-gemara-slot-preview.png') });
  }

  // ── D + E. Developer Mode in the editor ──
  // Create the sample project to enter the editor (sample starter).
  await page.locator('[data-testid="new-project-form-home-submit"]').click();
  await page.waitForTimeout(2500);
  check('D status-bar QA button hidden when OFF', await page.locator('[data-testid="statusbar-qa-button"]').count() === 0);
  check('D QA score still visible as plain text', await page.locator('[data-testid="statusbar-qa-score"]').count() === 1);
  check('D no Automated Tests entry anywhere when OFF', (await page.locator('text=בדיקות אוטומטיות').count()) === 0);
  await page.screenshot({ path: path.join(SHOTS, '04-editor-dev-off.png') });

  await page.keyboard.press('Control+Shift+D');
  await page.waitForTimeout(600);
  check('E Ctrl+Shift+D shows the QA button', await page.locator('[data-testid="statusbar-qa-button"]').count() === 1);
  check('E developer mode persisted ON', (await page.evaluate(() => localStorage.getItem('keter-developer-mode'))) === '1');
  await page.screenshot({ path: path.join(SHOTS, '05-editor-dev-on.png') });

  await page.keyboard.press('Control+Shift+D');
  await page.waitForTimeout(600);
  check('E Ctrl+Shift+D again hides the QA button', await page.locator('[data-testid="statusbar-qa-button"]').count() === 0);
  check('E developer mode persisted OFF', (await page.evaluate(() => localStorage.getItem('keter-developer-mode'))) === '0');

  // ── F. English mode — fresh page, UI language forced to English ──
  // (A new page = a fresh browser context; addInitScript sets the
  // stored language before the app boots, so it renders in English
  // from the first paint. The Welcome modal reappears and is dismissed
  // the same way — its close button reads "Close" in English mode.)
  const pageEn = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  pageEn.on('pageerror', (e) => errors.push(String(e)));
  pageEn.on('console', (m) => {
    if (m.type() === 'error' && !String(m.text()).startsWith('Failed to load resource')) errors.push(m.text());
  });
  pageEn.on('requestfailed', (req) => failedRequests.push(req.url()));
  await pageEn.addInitScript(() => localStorage.setItem('keter-ui-lang', 'en'));
  await pageEn.goto(base + '/', { waitUntil: 'networkidle' });
  await pageEn.waitForTimeout(1500);
  await dismissWelcomeModal(pageEn);
  check('F document.dir is ltr in English mode', (await pageEn.evaluate(() => document.documentElement.dir)) === 'ltr');
  const stepperEn = await pageEn.locator('[data-testid="sefer-wizard-stepper"]').innerText();
  check('F stepper renders in English', stepperEn.includes('New Sefer Wizard:') && stepperEn.includes('Choose a book type'), stepperEn);
  check('F stepper has no Hebrew wizard text', !stepperEn.includes('אשף ספר חדש'));
  check('F stepper arrow points right in LTR', stepperEn.includes('→') && !stepperEn.includes('←'), stepperEn);
  const shasCardEn = pageEn.locator('[data-testid="new-project-form-home-wizard-archetype-shas"]');
  check('F Shas archetype card is English', (await shasCardEn.innerText()).includes('Shas / Gemara'));
  await shasCardEn.click();
  await pageEn.waitForTimeout(600);
  check('F slot matrix title is English', (await pageEn.locator('[data-testid="docx-hub-home-wizard-slots"]').innerText()).includes('Step 2 — Word files by role (Shas / Gemara):'));
  check('F Add Another Mefaresh button is English', (await pageEn.locator('[data-testid="docx-hub-home-add-mefaresh"]').innerText()).includes('Add another mefaresh'));
  check('F Step-3 note is English', (await pageEn.locator('[data-testid="docx-hub-home-wizard-step3-note"]').innerText()).includes('Step 3 — Generate the sefer layout:'));
  check('F Generate button is English', (await pageEn.locator('text=Generate sefer layout (step 3)').count()) >= 1);
  if (gemaraFile) {
    const slotInputEn = pageEn.locator('[data-testid="docx-hub-home-slot-gemara"] input[type="file"]');
    await slotInputEn.setInputFiles(path.join(FIXTURES, gemaraFile));
    await pageEn.waitForFunction(
      () => document.querySelector('[data-testid="docx-hub-home-preview-gemara"]')?.textContent?.includes('Words'),
      { timeout: 15000 }
    );
    const previewEn = await pageEn.locator('[data-testid="docx-hub-home-preview-gemara"]').innerText();
    check('F per-file preview counts are English', /Words/.test(previewEn) && /Verses/.test(previewEn) && !/מילים/.test(previewEn), previewEn);
  }
  await pageEn.screenshot({ path: path.join(SHOTS, '06-wizard-en.png') });
  await pageEn.close();

  // No JS exceptions and no console errors on either page. Failed
  // requests are judged by origin: same-origin failures (a missing
  // dist asset) fail the run; external ones (the Google Fonts CSS the
  // app fetches at runtime) are reported as an environment note — the
  // sandbox proxy blocks that host, and the app falls back to system
  // fonts. Pre-existing: no font files ship in the repo (see
  // PHASE-1-2.md), so this is not a v0.9.8 regression.
  check('no JS page errors during the drive', errors.length === 0, errors.slice(0, 3).join(' | '));
  const sameOriginFailures = failedRequests.filter((u) => u.startsWith(base));
  check('no same-origin resource failed to load', sameOriginFailures.length === 0, sameOriginFailures.join(' | '));
  const externalFailures = [...new Set(failedRequests.filter((u) => !u.startsWith(base)))];
  if (externalFailures.length > 0) console.log(`  (note) external resource unreachable in this sandbox: ${externalFailures.join(' | ')}`);
} finally {
  await browser.close();
  server.close();
}

console.log(`\nv098-phase1-playwright-smoke: ${passes} passed, ${failures} failed`);
process.exit(failures > 0 ? 1 : 0);
