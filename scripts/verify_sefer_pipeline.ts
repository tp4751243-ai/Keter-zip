/**
 * KETER-TYPE v0.9.8 Phase 6 — end-to-end Sefer pipeline verification.
 *
 * Run from the repo root (fonts are needed for the PDF gates):
 *   KETER_FONTS_DIR=/tmp/keter-fonts npx tsx scripts/verify_sefer_pipeline.ts
 * Without KETER_FONTS_DIR (or public/fonts) the PDF gates are SKIPPED
 * with a reason — same gate as scripts/partE-smoke.ts — and the import /
 * link / paginate / IDML gates still run and must pass. No font files
 * ship in the repo; see scripts/v098-phase6-smoke.ts for how the test
 * fonts were obtained (OFL, fetched for the test run only).
 *
 * Pipeline under test (the real user flow, not an in-memory shortcut):
 *   synthetic .docx fixtures (Gemara + Rashi + Tosafot, nikkud,
 *   citations, 50+ dibburim — generated by
 *   scripts/v098-make-test-docx.py into a temp dir)
 *     → DocxImporter.importDocx (per file, role by slot as the hub does)
 *     → CommentaryLinkerEngine.linkCommentariesToSource
 *     → PaginationEngine.paginateDocument (rav_text)
 *     → PdfExporter.generateMultiPagePdf + IdmlExporter.generateMultiPageIdml
 *
 * Gates (all four must pass; a skipped PDF gate is reported, not hidden):
 *  G1  0 overlapping text boxes (PDF plan boxes + IDML frame polygons +
 *      the IDML package audit).
 *  G2  >95% Dibbur HaMaschil same-page co-location (linked dibburim
 *      only; the 8 deliberate orphan dibburim in the fixtures are
 *      expected to stay unlinked).
 *  G3  Valid RTL glyph ordering (extracted PDF text in logical order).
 *  G4  Non-empty valid PDF/IDML artifacts (magic bytes, page/frame
 *      counts, IDML audit pass, word-count conservation).
 *
 * Exit code 0 = every gate passed (skips do not fail); 1 = a failure.
 */

import { DOMParser } from '@xmldom/xmldom';
(globalThis as unknown as { DOMParser: typeof DOMParser }).DOMParser = DOMParser;
(globalThis as unknown as { Node: unknown }).Node = { ELEMENT_NODE: 1, TEXT_NODE: 3 };

import * as fs from 'node:fs';
import * as os from 'node:os';
import * as path from 'node:path';
import { execSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { DocxImporter } from '../src/engine/docx-importer';
import {
  linkCommentariesToSource,
  anchorLinksToRavTextLinks,
} from '../src/engine/commentary-linker';
import { PaginationEngine } from '../src/engine/pagination-engine';
import { PdfExporter } from '../src/engine/pdf-exporter';
import { PdfNativeTextEngine } from '../src/engine/pdf-native-text-engine';
import { IdmlExporter } from '../src/engine/idml-exporter';
import { DesignSettingsEngine } from '../src/engine/design-settings-engine';
import { findDibburWordKey, findTargetWordKey } from '../src/engine/anchor-overlay';
import type { ContentRole, ContentUnit } from '../src/types/typesetter';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'));

let passes = 0;
let failures = 0;
let skips = 0;
function check(name: string, ok: boolean, detail = '') {
  if (ok) {
    passes++;
    console.log(`  PASS  ${name}${detail ? ` — ${detail}` : ''}`);
  } else {
    failures++;
    console.log(`  FAIL  ${name}${detail ? ` — ${detail}` : ''}`);
  }
}
function skip(name: string, reason: string) {
  skips++;
  console.log(`  SKIP  ${name} — ${reason}`);
}

const GEOMETRY = { pageWidth: 482, pageHeight: 680, marginTop: 48, marginBottom: 48, marginInside: 46, marginOutside: 42, isVerso: false };
const mLeft = GEOMETRY.marginInside;
const mTop = GEOMETRY.marginTop;

async function main(): Promise<void> {
  console.log('== verify_sefer_pipeline — v0.9.8 ==');

  // ── Fixtures ───────────────────────────────────────────────────────────
  const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'keter-v098-pipeline-'));
  execSync(`python3 ${path.join(ROOT, 'scripts', 'v098-make-test-docx.py')} ${tmpDir}`, { stdio: 'pipe' });
  const fixtureFiles = ['gemara-50.docx', 'rashi-50.docx', 'tosafot-50.docx'];
  for (const f of fixtureFiles) {
    check(`fixture ${f} generated`, fs.existsSync(path.join(tmpDir, f)));
  }

  // ── Import (role by slot, exactly as the DocxImportHub assigns) ────────
  const slotRole: Record<string, ContentRole> = {
    'gemara-50.docx': 'main_source',
    'rashi-50.docx': 'primary_comment',
    'tosafot-50.docx': 'secondary_comment',
  };
  const units: ContentUnit[] = [];
  const sources: ContentUnit[] = [];
  const commentaries: ContentUnit[] = [];
  for (const f of fixtureFiles) {
    const buf = fs.readFileSync(path.join(tmpDir, f));
    const res = await DocxImporter.importDocx(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength) as ArrayBuffer, f);
    const role = slotRole[f];
    console.log(`  INFO  ${f}: ${res.units.length} units, importer detected roles [${res.metadata.detectedRoles.join(', ')}], hasNikud=${res.metadata.hasNikud}, paragraphs=${res.metadata.totalParagraphs}`);
    for (const u of res.units) {
      u.role = role;
      u.order = units.length;
      units.push(u);
      if (role === 'main_source') sources.push(u);
      else commentaries.push(u);
    }
  }
  check('all three parts imported', sources.length > 0 && commentaries.length > 0, `${sources.length} source units, ${commentaries.length} commentary units`);
  const dibburUnits = commentaries.filter(u => u.dibburHamatchil && u.dibburHamatchil.trim().length > 0);
  check('commentary units carry tokenized dibburim', dibburUnits.length >= 50, `${dibburUnits.length} dibburim`);

  // ── Link ───────────────────────────────────────────────────────────────
  const anchorLinks = linkCommentariesToSource(sources, commentaries);
  const linked = anchorLinks.filter(a => a.targetMainNodeId);
  check('linker links the matched dibburim', linked.length >= 95, `${linked.length} linked of ${anchorLinks.length} (8 deliberate orphans expected unlinked)`);
  for (const a of anchorLinks) {
    const com = commentaries.find(u => u.id === a.commentaryUnitId);
    if (com) com.anchorLink = a;
  }

  // ── Paginate ───────────────────────────────────────────────────────────
  const settings = DesignSettingsEngine.createDefaultSettings({ layoutType: 'rav_text', geometry: GEOMETRY });
  const doc = PaginationEngine.paginateDocument({
    title: 'Pipeline verification sefer',
    layoutType: 'rav_text',
    units,
    links: anchorLinksToRavTextLinks(anchorLinks, units),
    anchorLinks,
    geometry: GEOMETRY,
    sourceFontSize: 14.5,
    commentaryFontSize: 10.5,
    designSettings: settings,
  });
  check('book paginates to multiple pages', doc.pages.length >= 2, `${doc.pages.length} pages`);

  // ── G1: 0 overlapping text boxes ───────────────────────────────────────
  // (a) PDF plan boxes: no two line boxes on one page intersect in both
  //     axes by more than 0.5pt; no two words on one line overlap in x.
  let planOverlaps = 0;
  let planLinesTotal = 0;
  for (const page of doc.pages) {
    const plan = PdfExporter.buildPageRenderPlan(page);
    planLinesTotal += plan.lines.length;
    const boxes = plan.lines.map(l => ({ x0: l.xLeft, x1: l.xRight, y0: l.yTop, y1: l.yBottom, id: `${l.unitId}:${l.lineIndex}` }));
    for (let i = 0; i < boxes.length; i++) {
      for (let j = i + 1; j < boxes.length; j++) {
        const a = boxes[i];
        const b = boxes[j];
        if (Math.min(a.x1, b.x1) - Math.max(a.x0, b.x0) > 0.5 && Math.min(a.y1, b.y1) - Math.max(a.y0, b.y0) > 0.5) {
          planOverlaps++;
          if (planOverlaps <= 3) console.log(`    overlap: ${a.id} vs ${b.id}`);
        }
      }
    }
    for (const l of plan.lines) {
      const words = [...l.words].sort((x, y) => x.xLeft - y.xLeft);
      for (let i = 1; i < words.length; i++) {
        if (words[i].xLeft < words[i - 1].xRight - 0.5) planOverlaps++;
      }
    }
  }
  check('G1a PDF plan: 0 overlapping text boxes', planOverlaps === 0, `${planLinesTotal} lines checked, ${planOverlaps} overlaps`);
  // (b) IDML frame polygons.
  let idmlOverlaps = 0;
  for (const page of doc.pages) {
    const { frames } = IdmlExporter.computePageTextFrames(page, page.pageIndex);
    for (let i = 0; i < frames.length; i++) {
      for (let j = i + 1; j < frames.length; j++) {
        if (IdmlExporter.doPolygonsOverlap(frames[i].polygonPoints, frames[j].polygonPoints, 1.0)) idmlOverlaps++;
      }
    }
  }
  check('G1b IDML frames: 0 overlapping text boxes', idmlOverlaps === 0, `${idmlOverlaps} overlapping pairs`);

  // ── G2: Dibbur same-page co-location >95% ─────────────────────────────
  const unitsById = new Map(units.map(u => [u.id, u]));
  let colocated = 0;
  let colocChecked = 0;
  for (const link of linked) {
    const targetUnit = unitsById.get(link.targetMainNodeId ?? '');
    if (!targetUnit || link.targetCharOffset === undefined) continue;
    let targetPage = -1;
    let dibburPage = -1;
    for (const page of doc.pages) {
      if (targetPage < 0 && findTargetWordKey(page, targetUnit, link.targetCharOffset)) targetPage = page.pageIndex;
      if (dibburPage < 0 && findDibburWordKey(page, link.commentaryUnitId)) dibburPage = page.pageIndex;
      if (targetPage >= 0 && dibburPage >= 0) break;
    }
    if (targetPage >= 0 && dibburPage >= 0) {
      colocChecked++;
      if (targetPage === dibburPage) colocated++;
    }
  }
  check('G2 Dibbur same-page co-location >95%', colocChecked > 0 && colocated / colocChecked > 0.95, `${colocated}/${colocChecked} (${colocChecked ? ((100 * colocated) / colocChecked).toFixed(1) : '0'}%)`);

  // ── IDML artifact (G4, IDML half) ──────────────────────────────────────
  const idmlBlob = await IdmlExporter.generateMultiPageIdml(doc);
  const idmlHead = new Uint8Array(await idmlBlob.slice(0, 2).arrayBuffer());
  check('G4a IDML artifact is a non-empty valid ZIP', idmlBlob.size > 1000 && idmlHead[0] === 0x50 && idmlHead[1] === 0x4b, `${idmlBlob.size} bytes`);
  const audit = await IdmlExporter.auditIdmlPackage(idmlBlob, doc);
  check('G4b IDML package audit passes', audit.passed, audit.errors.join('; ') || `${audit.totalTextFrames} frames`);
  check('G1c IDML audit: 0 overlapping frames', (audit.overlappingTextFrames?.length ?? 0) === 0);
  check('G4c IDML conserves the word count', audit.conservedWordCount === audit.expectedWordCount && audit.expectedWordCount > 0, `${audit.conservedWordCount}/${audit.expectedWordCount}`);
  fs.writeFileSync(path.join(tmpDir, 'pipeline.idml'), Buffer.from(await idmlBlob.arrayBuffer()));

  // ── PDF artifact + G3 RTL (fonts gate) ─────────────────────────────────
  const FONT_FILES = [
    'FrankRuhlLibre-Regular.ttf',
    'FrankRuhlLibre-Bold.ttf',
    'NotoRashiHebrew-Regular.ttf',
    'NotoRashiHebrew-Bold.ttf',
    'DavidLibre-Regular.ttf',
    'DavidLibre-Bold.ttf',
  ];
  const fontDir = process.env.KETER_FONTS_DIR
    ? path.resolve(process.env.KETER_FONTS_DIR)
    : path.join(ROOT, 'public', 'fonts');
  const fontsAvailable = FONT_FILES.every(f => fs.existsSync(path.join(fontDir, f)));
  if (!fontsAvailable) {
    skip('G4d PDF artifact', `font binaries not in ${fontDir} — set KETER_FONTS_DIR`);
    skip('G3 valid RTL glyph ordering', 'no PDF (fonts missing)');
    skip('G1d PDF extracted positions vs plan', 'no PDF (fonts missing)');
  } else {
    const pdfBlob = await PdfExporter.generateMultiPagePdf(doc, undefined, { purpose: 'print', bleedMm: 0 });
    const pdfHead = new Uint8Array(await pdfBlob.slice(0, 5).arrayBuffer());
    check('G4d PDF artifact is a non-empty valid PDF', pdfBlob.size > 1000 && String.fromCharCode(...pdfHead) === '%PDF-', `${pdfBlob.size} bytes`);
    fs.writeFileSync(path.join(tmpDir, 'pipeline.pdf'), Buffer.from(await pdfBlob.arrayBuffer()));
    const extracted = await PdfNativeTextEngine.extractTextAndPositionsFromPdf(pdfBlob);
    check('G4e extracted PDF has the same page count', extracted.pageCount === doc.pages.length, `${extracted.pageCount} pages`);
    const norm = (s: string) => s.replace(/[\s״׳"'-]+/g, '');
    let matched = 0;
    let checked = 0;
    let rtlOk = 0;
    let rtlChecked = 0;
    for (const page of doc.pages) {
      const plan = PdfExporter.buildPageRenderPlan(page);
      const extPage = extracted.pages[page.pageIndex];
      if (!extPage) continue;
      for (const pl of plan.lines) {
        const expected = norm(pl.words.map(w => w.text).join(''));
        if (expected.length < 4) continue;
        checked++;
        const near = extPage.lines.filter(l => Math.abs(l.yBaselinePt - pl.yBaseline) <= 2);
        const union = near.map(l => norm(l.lineText)).join('|');
        if (near.length > 0 && union.includes(expected)) {
          matched++;
          const revWords = norm([...pl.words.map(w => w.text)].reverse().join(''));
          if (revWords !== expected) {
            rtlChecked++;
            if (!union.includes(revWords)) rtlOk++;
          }
        }
      }
    }
    check('G1d PDF extracted text lands on plan baselines (≤2pt)', checked > 0 && matched / checked >= 0.95, `${matched}/${checked}`);
    check('G3 valid RTL glyph ordering (logical order, not word-reversed)', rtlChecked > 0 && rtlOk / rtlChecked >= 0.95, `${rtlOk}/${rtlChecked} lines`);
  }

  check('version is 0.9.8', pkg.version === '0.9.8', pkg.version);
  console.log(`  INFO  artifacts saved in ${tmpDir}`);
  console.log(`\nverify_sefer_pipeline: ${passes} passed, ${failures} failed, ${skips} skipped`);
  process.exit(failures === 0 ? 0 : 1);
}

main().catch(e => {
  console.error('verify_sefer_pipeline crashed:', e);
  process.exit(1);
});
