/**
 * v0.9.0 Part A — layout recipe engine (`.keter-template.json`).
 *
 * A *layout recipe* is a versioned, portable description of a historical
 * page layout: where each tier of text sits (regions), how the tiers flow
 * into each other (flow bindings), how the text is set (typography) and
 * what the page looks like (page geometry + header/footer rules).
 *
 * Everything here is offline and deterministic, with no React and no I/O.
 * A recipe is plain JSON data: `serializeRecipe` / `deserializeRecipe`
 * round-trip it byte-for-byte (field order aside), and `validateRecipe`
 * is strict — a recipe with bad geometry is rejected with errors, never
 * silently accepted and never silently "fixed" into a different layout.
 *
 * Applying a recipe (`applyRecipeToSettings`) maps it onto the settings
 * the pagination engine already understands: the recipe's regions become
 * `CustomLayoutBox`es (see `custom-layout-engine.ts`), its page geometry
 * becomes the settings geometry, its tiers become `pageLayout.tiers`,
 * and its typography/header rules become role styles / page-element
 * settings — all through the public `DesignSettingsEngine` setters.
 * The book then paginates through the existing `custom_layout` path
 * (`PaginationEngine.paginateDocument`, layoutType `'custom_layout'`),
 * so a recipe that cannot render is a recipe that fails the smoke test,
 * not a recipe that silently produces a different page.
 *
 * Honest limits (kept here so Part C does not have to rediscover them):
 * - Flanks are resolved for the RECTO (first body) page: in a Hebrew
 *   book the recto is the left-hand page of the spread, so 'inside' =
 *   right and 'outside' = left. `recipeToCustomLayoutBoxes` mirrors the
 *   whole page when `facingPage: 'verso'` is passed; the pagination
 *   engine itself does not mirror boxes per page, so a book applied
 *   from a recipe uses the recto orientation on every page until Part C
 *   wires per-page overrides.
 * - The custom-layout box flow is role-based, not unit-based: several
 *   commentary boxes all accept the same comment roles, so named
 *   commentaries (e.g. Magen Avraham vs. Biur HaGra) flow into their
 *   columns in book order. A region's `labelHe` / `namedCommentary`
 *   records WHICH commentary the column is for; binding a specific
 *   unit stream to a specific box needs a Part C/D unit→box binding.
 * - `typography.justification.expansion: 'kashya'` and the dibbur
 *   `brackets` / `separator` are recorded in the recipe (they are part
 *   of the historical record) but the engine has no settings field for
 *   them yet: justification today is the engine's word-spacing
 *   justification, and dibbur rendering is bold + keep-together. They
 *   are NOT silently mapped to something else.
 * - The `footer` tier role has no box: folio text is generated by the
 *   engine, so a footer region is validated as layout metadata and
 *   applied to the page-element settings (folio position/style), not
 *   turned into a text box.
 * - A `header` region DOES become a box (it receives `heading` /
 *   `chapter` / `main_title` units), but a recipe may also carry its
 *   running header as a header/footer RULE (e.g. the Siddur's centred
 *   "מנחה לשבת") instead of a box — in that case section headings stay
 *   in the main-text flow, which is where they belong in a siddur.
 */

