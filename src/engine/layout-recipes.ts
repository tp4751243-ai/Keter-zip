/** Box tier → recipe tier role (designer tiers are the 11 UI tiers). */
const BOX_TIER_TO_RECIPE_ROLE: Record<CustomLayoutBoxTier, LayoutRecipeTierRole> = {
  main_text: 'main_text',
  main_drush: 'drush',
  rashi: 'rashi',
  tosafot: 'tosafot',
  side_gloss: 'gloss',
  bottom_note: 'footnote',
  marginal_citation: 'citation',
  footnote: 'footnote',
  header: 'header',
  footer: 'footer',
  commentary: 'commentary_1',
};

function customLayoutBoxToRegion(box: CustomLayoutBox, index: number): LayoutRecipeRegion {
  const role = BOX_TIER_TO_RECIPE_ROLE[box.tier ?? 'commentary'] ?? 'commentary_1';
  const shape: RecipeRegionShape =
    box.shape?.kind === 'custom' && box.shape.points.length >= 3
      ? {
          kind: 'polygon',
          vertices: box.shape.points.map(p => ({
            x: box.xPct + (p.x * box.widthPct) / 100,
            y: box.yPct + (p.y * box.heightPct) / 100,
          })),
        }
      : { kind: 'rect', x: box.xPct, y: box.yPct, w: box.widthPct, h: box.heightPct };
  return {
    id: box.id || `box-${index + 1}`,
    role,
    labelHe: box.labelHe,
    labelEn: box.labelEn,
    shape,
    units: '%',
    origin: 'content-box',
    ...(box.fontSizePt !== undefined ? { fontSizePt: box.fontSizePt } : {}),
    ...(box.lineHeight !== undefined ? { lineHeight: box.lineHeight } : {}),
    ...(box.rules?.lineHeightRatio !== undefined ? { lineHeight: box.rules.lineHeightRatio } : {}),
    ...(box.rules?.columnGutterPt !== undefined ? { gutterMm: box.rules.columnGutterPt / PT_PER_MM } : {}),
    // v0.9.2 Part A (A1): the rule-inspector clamp + alignment ride on
    // the region so a template round-trips them (regionToBox restores).
    ...(box.rules?.minFontSizePt !== undefined ? { minFontSizePt: box.rules.minFontSizePt } : {}),
    ...(box.rules?.maxFontSizePt !== undefined ? { maxFontSizePt: box.rules.maxFontSizePt } : {}),
    ...(box.rules?.alignment !== undefined ? { alignment: box.rules.alignment } : {}),
  };
}

/**
 * Build a `.keter-template.json` recipe from the Designer's boxes
 * (the local export path — no settings object needed). Regions are the
 * boxes in '%' of the content box, so the template re-applies at any
 * page size. Page geometry is a neutral A4 default: a designer export
 * carries box geometry, not a page size — the library recipes carry
 * their own exact geometry.
 */
export function recipeFromBoxes(
  boxes: CustomLayoutBox[],
  baseLayout: BookLayoutType,
  meta: { nameHe?: string; nameEn?: string },
): LayoutRecipe {
  const name = meta.nameEn ?? meta.nameHe ?? 'Custom template';
  return {
    keterTemplateVersion: KETER_TEMPLATE_VERSION,
    metadata: {
      id: 'custom-template',
      name,
      nameHe: meta.nameHe,
      description: 'Custom layout from the Manuscript & Custom Layout Designer.',
      genre: ['custom'],
      origin: 'Keter Typesetter',
    },
    regions: boxes.map((b, i) => customLayoutBoxToRegion(b, i)),
    flow: [],
    page: {
      widthMm: 210,
      heightMm: 297,
      marginTopMm: 20,
      marginBottomMm: 20,
      marginInsideMm: 20,
      marginOutsideMm: 20,
    },
    baseLayout,
  };
}
