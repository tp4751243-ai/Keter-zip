/**
 * Balance a multi-tier grid across the content width: tier widths are
 * normalised so they sum to 100% minus gutters, and the gutter shrinks as
 * the tier count grows (6 tiers get a narrower gutter than 2), so no tier
 * is ever squeezed to zero and no tier ever overlaps its neighbour.
 * Pure — returns new tier configs. Rescaling is proportional, so every
 * ratio the knee solver reads (flank share, column split, source share)
 * is unchanged by balancing; only the stored widths become sane.
 * NOTE (honest): the rav_text paginator still renders tiers 4–7 in ONE
 * shared tertiary band below the knee (see v0.8.0 Part C §2); this grid
 * governs the settings-level widths the knee solver and the
 * bottom-commentary split read, and the Mikraot paginator's per-tier
 * bands where they exist. It does not by itself make the renderer draw
 * six separate bands.
 * v0.9.2 Part A (A4): moved here from auto-layout.ts and wired into
 * applyRecipeToSettings below — it was exported but never called in
 * production, so every library recipe landed tier widths summing to
 * 188–462% (stacked regions each contribute their full width).
 */
export function balanceTierGrid(
  tiers: TierConfig[],
  contentWidthPt: number
): { tiers: TierConfig[]; gutterPt: number; notes: string[] } {
  const notes: string[] = [];
  if (tiers.length === 0) return { tiers: [], gutterPt: 12, notes };
  const count = tiers.length;
  // Gutter scales down with tier count: 12pt for 2 tiers → 6pt for 6+.
  const gutterPt = Math.max(6, Math.round(14 - count));
  const totalGutterPct = ((count - 1) * gutterPt) / Math.max(1, contentWidthPt) * 100;
  const widthSum = tiers.reduce((s, t) => s + (t.widthPct ?? 0), 0);
  const available = Math.max(10, 100 - totalGutterPct);
  const scaled = tiers.map(t => {
    const w = t.widthPct ?? available / count;
    const next = widthSum > 0 ? (w / widthSum) * available : available / count;
    return { ...t, widthPct: Math.max(5, Math.round(next * 10) / 10) };
  });
  if (widthSum > available) {
    notes.push(`Tier widths rescaled to fit ${available.toFixed(0)}% of the content width (${count} tiers, ${gutterPt}pt gutters).`);
  }
  if (count > 3) {
    notes.push(`${count} tiers: gutter narrowed to ${gutterPt}pt so every tier keeps a readable width.`);
  }
  return { tiers: scaled, gutterPt, notes };
}

/** Tier list for the recipe, in tier order (main text first). */
export function recipeToTierConfigs(recipe: LayoutRecipe): TierConfig[] {
  const order: LayoutRecipeTierRole[] = [
    'main_text', 'drush', 'rashi', 'tosafot',
    'commentary_1', 'commentary_2', 'commentary_3',
    'commentary_4', 'commentary_5', 'commentary_6',
    'gloss', 'footnote', 'header', 'marginal', 'citation',
  ];
  const byRole = new Map<LayoutRecipeTierRole, LayoutRecipeRegion>();
  for (const region of recipe.regions) {
    if (!byRole.has(region.role)) byRole.set(region.role, region);
  }
  const tiers: TierConfig[] = [];
  let idx = 0;
  for (const role of order) {
    const region = byRole.get(role);
    if (!region) continue;
    idx += 1;
    if (idx > 7) break; // TierConfig supports 1 main + 6 comment tiers.
    const rect = regionRectToContentPct(region, recipe.page, 'recto');
    const side: TierConfig['side'] =
      region.side === 'inside' ? 'inside'
      : region.side === 'outside' ? 'outside'
      : region.side === 'left' ? 'left'
      : region.side === 'right' ? 'right'
      : rect.x + rect.w / 2 < 50 ? 'left' : 'right';
    tiers.push({
      role: RECIPE_ROLE_TO_CONTENT_ROLE[role],
      tierIndex: idx,
      labelHe: region.labelHe,
      labelEn: region.labelEn,
      widthPct: Math.max(5, Math.min(90, Math.round(rect.w))),
      fontSizePt: region.fontSizePt ?? recipe.typography?.commentaryFontSizePt ?? recipe.typography?.mainFontSizePt,
      lineHeight: region.lineHeight,
      side,
    });
  }
  return tiers;
}

