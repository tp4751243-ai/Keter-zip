function isFiniteNumber(v: unknown): v is number {
  return typeof v === 'number' && Number.isFinite(v);
}

function checkRegionShape(
  region: LayoutRecipeRegion,
  page: RecipePageGeometry,
  errors: string[],
): void {
  const where = `region '${region.id}'`;
  if (region.shape.kind === 'rect') {
    const { x, y, w, h } = region.shape;
    for (const [k, v] of [['x', x], ['y', y], ['w', w], ['h', h]] as const) {
      if (!isFiniteNumber(v)) errors.push(`${where}: rect.${k} must be a finite number.`);
    }
    if (!isFiniteNumber(w) || !isFiniteNumber(h)) return;
    if (w <= 0 || h <= 0) errors.push(`${where}: rect width/height must be > 0 (got ${w}×${h}).`);
    if (region.units === '%') {
      const maxW = region.origin === 'page' ? 100 : 100;
      const maxH = 100;
      if (x < 0 || y < 0 || x + w > maxW + 1e-9 || y + h > maxH + 1e-9) {
        errors.push(`${where}: rect ${x},${y} ${w}×${h}% runs outside the ${region.origin} (${maxW}×${maxH}%).`);
      }
    } else {
      const maxW = region.origin === 'page' ? page.widthMm : page.widthMm - page.marginInsideMm - page.marginOutsideMm;
      const maxH = region.origin === 'page' ? page.heightMm : page.heightMm - page.marginTopMm - page.marginBottomMm;
      if (x < 0 || y < 0 || x + w > maxW + 1e-9 || y + h > maxH + 1e-9) {
        errors.push(`${where}: rect ${x},${y} ${w}×${h}mm runs outside the ${region.origin} (${maxW}×${maxH}mm).`);
      }
    }
  } else if (region.shape.kind === 'polygon') {
    const vs = region.shape.vertices;
    if (!Array.isArray(vs) || vs.length < 3) {
      errors.push(`${where}: polygon needs at least 3 vertices.`);
      return;
    }
    for (const [i, v] of vs.entries()) {
      if (!isFiniteNumber(v.x) || !isFiniteNumber(v.y)) {
        errors.push(`${where}: vertex ${i} must have finite x/y.`);
        continue;
      }
      if (region.units === '%') {
        const maxX = region.origin === 'page' ? 100 : 100;
        if (v.x < 0 || v.x > maxX || v.y < 0 || v.y > 100) {
          errors.push(`${where}: vertex ${i} (${v.x},${v.y}) is outside the ${region.origin}.`);
        }
      } else {
        const maxX = region.origin === 'page' ? page.widthMm : page.widthMm - page.marginInsideMm - page.marginOutsideMm;
        const maxY = region.origin === 'page' ? page.heightMm : page.heightMm - page.marginTopMm - page.marginBottomMm;
        if (v.x < 0 || v.x > maxX || v.y < 0 || v.y > maxY) {
          errors.push(`${where}: vertex ${i} (${v.x},${v.y}) is outside the ${region.origin}.`);
        }
      }
    }
  } else {
    errors.push(`${where}: unknown shape kind '${(region.shape as { kind?: unknown }).kind}'.`);
  }
}

/**
 * Strict validation. Returns the list of problems; an empty list means
 * the recipe is well-formed. This checks the recipe's own geometry and
 * cross-field consistency — it does NOT check whether the regions
 * overlap (that is the box layer's job: `sanitizeCustomLayoutDesign`
 * reports overlaps when the recipe is applied).
 */
export function validateRecipe(recipe: unknown): string[] {
  const errors: string[] = [];
  if (!recipe || typeof recipe !== 'object') return ['Recipe must be an object.'];
  const r = recipe as Partial<LayoutRecipe>;

  if (r.keterTemplateVersion !== KETER_TEMPLATE_VERSION) {
    errors.push(`keterTemplateVersion must be ${KETER_TEMPLATE_VERSION} (got ${String(r.keterTemplateVersion)}).`);
  }
  const meta = r.metadata;
  if (!meta || typeof meta !== 'object') {
    errors.push('metadata is required.');
  } else {
    if (!meta.id || typeof meta.id !== 'string') errors.push('metadata.id is required.');
    else if (!/^[a-z0-9][a-z0-9-]*$/.test(meta.id)) errors.push(`metadata.id '${meta.id}' must be lowercase kebab-case.`);
    if (!meta.name || typeof meta.name !== 'string') errors.push('metadata.name is required.');
    if (!meta.description || typeof meta.description !== 'string') errors.push('metadata.description is required.');
    if (!Array.isArray(meta.genre)) errors.push('metadata.genre must be an array of tags.');
    if (!meta.origin || typeof meta.origin !== 'string') errors.push('metadata.origin is required.');
  }

  const page = r.page;
  if (!page || typeof page !== 'object') {
    errors.push('page geometry is required.');
    return errors;
  }
  for (const k of ['widthMm', 'heightMm', 'marginTopMm', 'marginBottomMm', 'marginInsideMm', 'marginOutsideMm'] as const) {
    if (!isFiniteNumber(page[k])) errors.push(`page.${k} must be a finite number.`);
  }
  if (isFiniteNumber(page.widthMm) && (page.widthMm < 50 || page.widthMm > 500)) {
    errors.push(`page.widthMm ${page.widthMm} is outside the plausible 50–500mm range.`);
  }
  if (isFiniteNumber(page.heightMm) && (page.heightMm < 50 || page.heightMm > 500)) {
    errors.push(`page.heightMm ${page.heightMm} is outside the plausible 50–500mm range.`);
  }
  if (
    isFiniteNumber(page.widthMm) && isFiniteNumber(page.marginInsideMm) && isFiniteNumber(page.marginOutsideMm) &&
    page.marginInsideMm + page.marginOutsideMm >= page.widthMm
  ) {
    errors.push('Horizontal margins leave no content width.');
  }
  if (
    isFiniteNumber(page.heightMm) && isFiniteNumber(page.marginTopMm) && isFiniteNumber(page.marginBottomMm) &&
    page.marginTopMm + page.marginBottomMm >= page.heightMm
  ) {
    errors.push('Vertical margins leave no content height.');
  }
  if (page.columns !== undefined && (!Number.isInteger(page.columns) || page.columns < 1 || page.columns > 3)) {
    errors.push('page.columns must be 1, 2 or 3.');
  }
  if (page.gutterMm !== undefined && (!isFiniteNumber(page.gutterMm) || page.gutterMm < 0)) {
    errors.push('page.gutterMm must be a non-negative number.');
  }

  // Alias entries carry no geometry of their own.
  if (r.aliasOf !== undefined) {
    if (typeof r.aliasOf !== 'string' || !r.aliasOf) errors.push('aliasOf must be a non-empty recipe id.');
    else if (r.aliasOf === meta?.id) errors.push('A recipe cannot alias itself.');
    if (Array.isArray(r.regions) && r.regions.length > 0) {
      errors.push(`Alias '${meta?.id ?? '?'}' points at '${r.aliasOf}' and must not carry its own regions.`);
    }
    return errors;
  }

  if (!Array.isArray(r.regions) || r.regions.length === 0) {
    errors.push('regions must be a non-empty array.');
  } else {
    const ids = new Set<string>();
    const roles = new Set<LayoutRecipeTierRole>();
    for (const region of r.regions) {
      if (!region || typeof region !== 'object') { errors.push('Every region must be an object.'); continue; }
      if (!region.id || typeof region.id !== 'string') errors.push('Every region needs a string id.');
      else if (ids.has(region.id)) errors.push(`Duplicate region id '${region.id}'.`);
      else ids.add(region.id);
      if (!LAYOUT_RECIPE_TIER_ROLES.includes(region.role)) {
        errors.push(`region '${region.id}': unknown tier role '${String(region.role)}'.`);
        continue;
      }
      roles.add(region.role);
      if (region.units !== 'mm' && region.units !== '%') {
        errors.push(`region '${region.id}': units must be 'mm' or '%' (got '${String(region.units)}').`);
      }
      if (region.origin !== 'page' && region.origin !== 'content-box') {
        errors.push(`region '${region.id}': origin must be 'page' or 'content-box' (got '${String(region.origin)}').`);
      }
      if (region.side !== undefined && !['left', 'right', 'inside', 'outside'].includes(region.side)) {
        errors.push(`region '${region.id}': side must be left/right/inside/outside.`);
      }
      if (region.paddingMm !== undefined && (!isFiniteNumber(region.paddingMm) || region.paddingMm < 0)) {
        errors.push(`region '${region.id}': paddingMm must be a non-negative number.`);
      }
      if (region.gutterMm !== undefined && (!isFiniteNumber(region.gutterMm) || region.gutterMm < 0)) {
        errors.push(`region '${region.id}': gutterMm must be a non-negative number.`);
      }
      if (region.aspectRatio !== undefined && (!isFiniteNumber(region.aspectRatio) || region.aspectRatio <= 0)) {
        errors.push(`region '${region.id}': aspectRatio must be > 0.`);
      }
      if (region.fontSizePt !== undefined && (!isFiniteNumber(region.fontSizePt) || region.fontSizePt < 6 || region.fontSizePt > 72)) {
        errors.push(`region '${region.id}': fontSizePt must be 6–72.`);
      }
      if (region.lineHeight !== undefined && (!isFiniteNumber(region.lineHeight) || region.lineHeight < 1.0 || region.lineHeight > 2.2)) {
        errors.push(`region '${region.id}': lineHeight must be 1.0–2.2.`);
      }
      // v0.9.2 Part A (A1): per-region rule-inspector fields.
      if (region.minFontSizePt !== undefined && (!isFiniteNumber(region.minFontSizePt) || region.minFontSizePt < 6 || region.minFontSizePt > 72)) {
        errors.push(`region '${region.id}': minFontSizePt must be 6–72.`);
      }
      if (region.maxFontSizePt !== undefined && (!isFiniteNumber(region.maxFontSizePt) || region.maxFontSizePt < 6 || region.maxFontSizePt > 72)) {
        errors.push(`region '${region.id}': maxFontSizePt must be 6–72.`);
      }
      if (
        region.minFontSizePt !== undefined && region.maxFontSizePt !== undefined &&
        region.maxFontSizePt < region.minFontSizePt
      ) {
        errors.push(`region '${region.id}': maxFontSizePt must be >= minFontSizePt.`);
      }
      if (region.alignment !== undefined && !['justify', 'right', 'center', 'left'].includes(region.alignment)) {
        errors.push(`region '${region.id}': alignment must be justify/right/center/left.`);
      }
      if (region.shape && region.units && region.origin) checkRegionShape(region, page, errors);
    }
    if (!roles.has('main_text') && !roles.has('drush')) {
      errors.push('At least one main-text region (main_text or drush) is required — a page with no main text cannot paginate.');
    }
  }

  if (!Array.isArray(r.flow)) {
    errors.push('flow must be an array (possibly empty).');
  } else {
    const knownRoles = new Set((r.regions ?? []).map(rg => rg?.role));
    for (const [i, b] of r.flow.entries()) {
      if (!b || typeof b !== 'object') { errors.push(`flow[${i}] must be an object.`); continue; }
      if (!LAYOUT_RECIPE_TIER_ROLES.includes(b.parentTier)) errors.push(`flow[${i}]: unknown parentTier '${String(b.parentTier)}'.`);
      if (!LAYOUT_RECIPE_TIER_ROLES.includes(b.childTier)) errors.push(`flow[${i}]: unknown childTier '${String(b.childTier)}'.`);
      if (b.parentTier === b.childTier) errors.push(`flow[${i}]: a tier cannot flow into itself.`);
      if (!['lineIndex', 'dibbur', 'heading', 'none'].includes(b.anchor)) {
        errors.push(`flow[${i}]: anchor must be lineIndex/dibbur/heading/none.`);
      }
      if (!['knee', 'outer-margin', 'next-folio'].includes(b.overflow)) {
        errors.push(`flow[${i}]: overflow must be knee/outer-margin/next-folio.`);
      }
      if (Array.isArray(r.regions) && r.regions.length > 0) {
        if (b.parentTier && !knownRoles.has(b.parentTier)) errors.push(`flow[${i}]: parentTier '${b.parentTier}' has no region.`);
        if (b.childTier && !knownRoles.has(b.childTier)) errors.push(`flow[${i}]: childTier '${b.childTier}' has no region.`);
      }
    }
  }

  const typo = r.typography;
  if (typo !== undefined) {
    if (typo.dibbur !== undefined) {
      if (!['none', 'square', 'round', 'colon'].includes(typo.dibbur.brackets)) {
        errors.push("typography.dibbur.brackets must be none/square/round/colon.");
      }
      if (typo.dibbur.weight !== undefined && ![400, 500, 600, 700].includes(typo.dibbur.weight)) {
        errors.push('typography.dibbur.weight must be 400/500/600/700.');
      }
    }
    if (typo.indentation !== undefined && !['first-line', 'second-line', 'none'].includes(typo.indentation.mode)) {
      errors.push("typography.indentation.mode must be first-line/second-line/none.");
    }
    if (typo.indentation?.amountPt !== undefined && (!isFiniteNumber(typo.indentation.amountPt) || typo.indentation.amountPt < 0 || typo.indentation.amountPt > 72)) {
      errors.push('typography.indentation.amountPt must be 0–72.');
    }
    if (typo.justification !== undefined && !['kashya', 'tracking', 'none'].includes(typo.justification.expansion)) {
      errors.push("typography.justification.expansion must be kashya/tracking/none.");
    }
    for (const k of ['mainFontSizePt', 'commentaryFontSizePt'] as const) {
      const v = typo[k];
      if (v !== undefined && (!isFiniteNumber(v) || v < 6 || v > 72)) errors.push(`typography.${k} must be 6–72.`);
    }
    if (typo.headingAlignment !== undefined && !['center', 'right', 'justify'].includes(typo.headingAlignment)) {
      errors.push("typography.headingAlignment must be center/right/justify.");
    }
  }

  const hf = r.headerFooter;
  if (hf !== undefined) {
    if (hf.folioStyle !== undefined && !['daf-amud', 'numbers', 'hebrew-letters', 'yerushalmi-abcd'].includes(hf.folioStyle)) {
      errors.push("headerFooter.folioStyle must be daf-amud/numbers/hebrew-letters/yerushalmi-abcd.");
    }
    if (hf.folioPosition !== undefined && !['outer-top', 'outer-bottom', 'inner-top', 'inner-bottom', 'top-center', 'bottom-center'].includes(hf.folioPosition)) {
      errors.push('headerFooter.folioPosition must be outer-top/outer-bottom/inner-top/inner-bottom/top-center/bottom-center.');
    }
    if (hf.runningHeaderAlignment !== undefined && !['left', 'center', 'right'].includes(hf.runningHeaderAlignment)) {
      errors.push("headerFooter.runningHeaderAlignment must be left/center/right.");
    }
  }

  return errors;
}

