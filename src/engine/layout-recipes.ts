/** JSON serialisation for a `.keter-template.json` file. */
export function serializeRecipe(recipe: LayoutRecipe): string {
  return JSON.stringify(recipe, null, 2);
}

/**
 * Parse + validate a `.keter-template.json` document. Throws on invalid
 * JSON or on any validation error (the message lists every error).
 */
export function deserializeRecipe(json: string): LayoutRecipe {
  let parsed: unknown;
  try {
    parsed = JSON.parse(json);
  } catch (e) {
    throw new Error(`Invalid recipe JSON: ${e instanceof Error ? e.message : String(e)}`);
  }
  const errors = validateRecipe(parsed);
  if (errors.length > 0) {
    throw new Error(`Invalid layout recipe:\n- ${errors.join('\n- ')}`);
  }
  return parsed as LayoutRecipe;
}

// ─────────────────────────────────────────────────────────────────────────────
// Geometry: recipe regions → custom-layout boxes (% of the content area)
// ─────────────────────────────────────────────────────────────────────────────

export interface RecipeToBoxesOptions {
  /** Recto = first body page (Hebrew book: left-hand page, inside = right). Default 'recto'. */
  facingPage?: 'recto' | 'verso';
}

interface RectPct {
  x: number;
  y: number;
  w: number;
  h: number;
}

/**
 * Resolve one region's shape to a rectangle in % of the CONTENT area.
 * - '%' + 'content-box': already content-relative — direct.
 * - '%' + 'page': % of the page; rescaled into the content area.
 * - 'mm' + 'page': millimetres from the page's top-left corner; the
 *   content area starts after the margins. For a Hebrew book the LEFT
 *   edge of a recto page is the OUTSIDE margin (binding on the right),
 *   and vice versa on verso.
 * - 'mm' + 'content-box': millimetres inside the content area.
 * Polygon regions resolve to their bounding rect here; the polygon
 * itself becomes the box's `shape` (see `regionToBox`).
 */
function regionRectToContentPct(
  region: LayoutRecipeRegion,
  page: RecipePageGeometry,
  facingPage: 'recto' | 'verso',
): RectPct {
  const pageWpt = page.widthMm * PT_PER_MM;
  const pageHpt = page.heightMm * PT_PER_MM;
  const marginTopPt = page.marginTopMm * PT_PER_MM;
  const marginBottomPt = page.marginBottomMm * PT_PER_MM;
  // Left-edge margin in LTR page coordinates: on a recto page the
  // binding is on the right, so the left edge is the outside margin.
  const marginLeftPt = (facingPage === 'recto' ? page.marginOutsideMm : page.marginInsideMm) * PT_PER_MM;
  const marginRightPt = (facingPage === 'recto' ? page.marginInsideMm : page.marginOutsideMm) * PT_PER_MM;
  const contentWpt = pageWpt - marginLeftPt - marginRightPt;
  const contentHpt = pageHpt - marginTopPt - marginBottomPt;

  let xMm: number;
  let yMm: number;
  let wMm: number;
  let hMm: number;
  if (region.shape.kind === 'rect') {
    if (region.units === '%') {
      const spanW = region.origin === 'page' ? page.widthMm : contentWpt / PT_PER_MM;
      const spanH = region.origin === 'page' ? page.heightMm : contentHpt / PT_PER_MM;
      xMm = (region.shape.x / 100) * spanW;
      yMm = (region.shape.y / 100) * spanH;
      wMm = (region.shape.w / 100) * spanW;
      hMm = (region.shape.h / 100) * spanH;
    } else {
      ({ x: xMm, y: yMm, w: wMm, h: hMm } = region.shape);
    }
  } else {
    const xs = region.shape.vertices.map(v => v.x);
    const ys = region.shape.vertices.map(v => v.y);
    const minX = Math.min(...xs);
    const minY = Math.min(...ys);
    const maxX = Math.max(...xs);
    const maxY = Math.max(...ys);
    if (region.units === '%') {
      const spanW = region.origin === 'page' ? page.widthMm : contentWpt / PT_PER_MM;
      const spanH = region.origin === 'page' ? page.heightMm : contentHpt / PT_PER_MM;
      xMm = (minX / 100) * spanW;
      yMm = (minY / 100) * spanH;
      wMm = ((maxX - minX) / 100) * spanW;
      hMm = ((maxY - minY) / 100) * spanH;
    } else {
      xMm = minX;
      yMm = minY;
      wMm = maxX - minX;
      hMm = maxY - minY;
    }
  }

  // Millimetres → pt, then into content-relative %.
  const xPt = xMm * PT_PER_MM - (region.origin === 'page' ? marginLeftPt : 0);
  const yPt = yMm * PT_PER_MM - (region.origin === 'page' ? marginTopPt : 0);
  const wPt = wMm * PT_PER_MM;
  const hPt = hMm * PT_PER_MM;
  let rect: RectPct = {
    x: (xPt / contentWpt) * 100,
    y: (yPt / contentHpt) * 100,
    w: (wPt / contentWpt) * 100,
    h: (hPt / contentHpt) * 100,
  };
  // Verso = mirror the whole page (Rashi/Tosafot swap sides, outer
  // margin moves to the other edge). See the module doc.
  if (facingPage === 'verso') {
    rect = { ...rect, x: 100 - rect.x - rect.w };
  }
  return rect;
}

/** One region → one `CustomLayoutBox` (footer regions produce no box). */
export function regionToBox(
  region: LayoutRecipeRegion,
  page: RecipePageGeometry,
  opts?: RecipeToBoxesOptions,
): CustomLayoutBox | null {
  const boxRole = RECIPE_ROLE_TO_BOX_ROLE[region.role];
  if (boxRole === null) return null;
  const facingPage = opts?.facingPage ?? 'recto';
  const rect = regionRectToContentPct(region, page, facingPage);
  const box = makeCustomLayoutBox(
    boxRole,
    rect.x,
    rect.y,
    rect.w,
    rect.h,
    region.labelHe,
  );
  box.id = `recipe-${region.id}`;
  if (region.labelEn) box.labelEn = region.labelEn;
  // v0.9.2 Part A (A1): restore the tier the region role encodes —
  // without this, an imported template lost every tier (a Rashi box
  // came back as a generic commentary box) even though the export had
  // written the tier into the region role. 'footnote' is ambiguous
  // (bottom_note and footnote both export as footnote); the plain
  // footnote tier is the safe default.
  const boxTier = RECIPE_ROLE_TO_BOX_TIER[region.role];
  if (boxTier) box.tier = boxTier;
  if (region.fontSizePt !== undefined) box.fontSizePt = region.fontSizePt;
  if (region.lineHeight !== undefined) box.lineHeight = region.lineHeight;
  // v0.9.2 Part A (A1): restore the rule-inspector values the export
  // writes onto the region, so a template round-trips them.
  const rules: CustomLayoutBoxRules = {};
  if (region.lineHeight !== undefined) rules.lineHeightRatio = region.lineHeight;
  if (region.gutterMm !== undefined) rules.columnGutterPt = region.gutterMm * PT_PER_MM;
  if (region.minFontSizePt !== undefined) rules.minFontSizePt = region.minFontSizePt;
  if (region.maxFontSizePt !== undefined) rules.maxFontSizePt = region.maxFontSizePt;
  if (region.alignment !== undefined) rules.alignment = region.alignment;
  const cleanRules = sanitizeCustomLayoutBoxRules(rules);
  if (cleanRules) box.rules = cleanRules;
  if (region.shape.kind === 'polygon') {
    const xs = region.shape.vertices.map(v => v.x);
    const ys = region.shape.vertices.map(v => v.y);
    const minX = Math.min(...xs);
    const minY = Math.min(...ys);
    const spanX = Math.max(...xs) - minX || 1;
    const spanY = Math.max(...ys) - minY || 1;
    let points = region.shape.vertices.map(v => ({
      x: (v.x - minX) / spanX,
      y: (v.y - minY) / spanY,
    }));
    if (facingPage === 'verso') points = points.map(p => ({ ...p, x: 1 - p.x }));
    const shape: CustomLayoutPolygonShape = { kind: 'custom', points };
    box.shape = shape;
  }
  return box;
}

/**
 * All of a recipe's regions as custom-layout boxes, in region order
 * (box order is fill order for the paginator: header first, then main
 * text, then commentaries, then footnotes/marginals).
 */
export function recipeToCustomLayoutBoxes(
  recipe: LayoutRecipe,
  opts?: RecipeToBoxesOptions,
): CustomLayoutBox[] {
  const boxes: CustomLayoutBox[] = [];
  for (const region of recipe.regions) {
    const box = regionToBox(region, recipe.page, opts);
    if (box) boxes.push(box);
  }
  return boxes;
}

