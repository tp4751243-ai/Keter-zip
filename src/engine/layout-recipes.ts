const PENDING_HISTORICAL_RECIPE_KEY = 'keter_pending_historical_recipe_v1';

export function consumePendingHistoricalRecipe(): string | null {
  try {
    const raw = localStorage.getItem(PENDING_HISTORICAL_RECIPE_KEY);
    if (!raw) return null;
    localStorage.removeItem(PENDING_HISTORICAL_RECIPE_KEY);
    return raw;
  } catch {
    return null;
  }
}

