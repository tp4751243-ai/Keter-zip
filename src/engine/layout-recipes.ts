function boxRoleToTierRole(box: CustomLayoutBox, commentarySeen: Map<string, number>): LayoutRecipeTierRole {
  switch (box.role) {
    case 'main_text': return 'main_text';
    case 'header': return 'header';
    case 'footnote': return 'footnote';
    case 'side_note': return 'marginal';
    case 'commentary': {
      const n = (commentarySeen.get('commentary') ?? 0) + 1;
      commentarySeen.set('commentary', n);
      return `commentary_${Math.min(6, n)}` as LayoutRecipeTierRole;
    }
  }
}

