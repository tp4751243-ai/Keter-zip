export interface LayoutRecipeRegion {
  id: string;
  role: LayoutRecipeTierRole;
  /** User-visible name, e.g. 'רש״י' / 'מגן אברהם'. Rendered as the column's running header. */
  labelHe?: string;
  labelEn?: string;
  /**
   * The specific named commentary this region holds, e.g.
   * 'Ein Mishpat Ner Mitzvah' / 'Magen Avraham' / 'Gilyon ha-Shas'.
   * Recorded for the reader and for Part C; the box flow itself is
   * role-based (see the module doc), so this does not by itself bind a
   * unit stream to this box.
   */
  namedCommentary?: string;
  shape: RecipeRegionShape;
  /** 'mm' = millimetres, '%' = percent of the origin's extent. */
  units: 'mm' | '%';
  /** 'page' = measured from the page's top-left corner; 'content-box' = inside the margins. */
  origin: 'page' | 'content-box';
  /**
   * Which physical side the region belongs to. 'left' / 'right' are
   * concrete; 'inside' / 'outside' are binding-relative and resolve
   * per facing page (recto: inside = right, outside = left — the
   * Hebrew-book rule). Purely descriptive for regions whose `shape`
   * already fixes their side; used by validation and by the smoke
   * checks that flanks sit on the right side.
   */
  side?: 'left' | 'right' | 'inside' | 'outside';
  /** Inner padding in mm (default 0). */
  paddingMm?: number;
  /** Gutter to the neighbouring region in mm (default 0). */
  gutterMm?: number;
  /** Width : height ratio the region should keep when resized (optional). */
  aspectRatio?: number;
  /** Per-region type size in pt (optional; unset = the role's size). */
  fontSizePt?: number;
  /** Per-region line-height multiplier 1.0..2.2 (optional). */
  lineHeight?: number;
  /** v0.9.2 Part A (A1): per-region font-size clamp, restored into the
   * box's rule inspector on import (export writes box.rules here). */
  minFontSizePt?: number;
  /** v0.9.2 Part A (A1): per-region font-size clamp, see minFontSizePt. */
  maxFontSizePt?: number;
  /** v0.9.2 Part A (A1): how the text inside the region is aligned. */
  alignment?: DesignAlignment;
}

